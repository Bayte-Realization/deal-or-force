import godot.gradle.GodotLanguage
import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import org.jetbrains.kotlin.gradle.tasks.KotlinCompile

plugins {
    id("com.utopia-rise.godot-jvm") version "1.0.0-rc4-SNAPSHOT"
}

repositories {
    mavenCentral()
    maven("https://central.sonatype.com/repository/maven-snapshots/")
}

godot {
    languages.set(setOf(GodotLanguage.KOTLIN))
    // Use the installed JDK without downloading another toolchain for this probe.
    // Game projects may instead select a reproducibly provisioned JDK 17 or newer.
    toolchain.javaVersion.set(providers.gradleProperty("dofJavaVersion").map { it.toInt() }.orElse(25))
}

// Build with the selected local JDK, but keep the sample runnable on JRE 17+.
// The JVM toolchain version and generated bytecode version are different knobs.
tasks.withType<KotlinCompile>().configureEach {
    compilerOptions.jvmTarget.set(JvmTarget.JVM_17)
}
tasks.withType<JavaCompile>().configureEach {
    options.release.set(17)
}
